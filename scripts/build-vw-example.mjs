import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import postcss from "postcss";
import pxToViewport from "postcss-px-to-viewport-8-plugin";
import config from "../postcss.config.mjs";

// The standalone HTML example uses exactly the same conversion as the H5.
const source = new URL("../public/examples/vw-card/card.vw.css", import.meta.url);
const target = new URL("../public/examples/vw-card/card.css", import.meta.url);
const result = await postcss([
  pxToViewport(config.plugins["postcss-px-to-viewport-8-plugin"]),
]).process(await readFile(source, "utf8"), {
  from: fileURLToPath(source), to: fileURLToPath(target), map: false,
});
await writeFile(target, `/* Generated by pnpm example:vw. Edit card.vw.css. */\n${result.css}`);
console.log("Generated public/examples/vw-card/card.css (750px → vw)");
